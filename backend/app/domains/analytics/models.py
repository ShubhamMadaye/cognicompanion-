"""
CogniCompanion — Analytics Domain Models
==========================================
SQLAlchemy 2.0 ORM models for performance tracking and CPI calculation:
  - daily_statistics   (derived daily aggregates)
  - cognitive_metrics  (CPI component scores per day)

These are DERIVED tables — background jobs compute values from:
  - game_sessions    → memory_accuracy, reaction_performance
  - medication_adherence_logs → medication_adherence
  - routine completion events → routine_adherence
  - assistant_interactions → engagement_score
"""

import uuid
from datetime import date, datetime, timezone

from sqlalchemy import Date, DateTime, Float, ForeignKey, Integer, String
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column

from app.core.database import Base


# ── daily_statistics ──────────────────────────────────────────────────────────

class DailyStatistic(Base):
    """
    Aggregated daily snapshot of patient performance.

    One row per (patient_id, stat_date).
    Generated by the analytics background job at end of day
    (or on-demand when the caregiver views the dashboard).

    Used by the caregiver dashboard for:
      - Today's activity summary (games ✓, medication ✓, routines ✓)
      - Weekly trend sparklines
    """
    __tablename__ = "daily_statistics"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4
    )
    patient_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("patients.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    stat_date: Mapped[date] = mapped_column(Date, nullable=False, index=True)

    # ── Games ─────────────────────────────────────────────────────────────────
    games_completed: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    games_total: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    average_game_accuracy: Mapped[float | None] = mapped_column(Float, nullable=True)  # 0.0–1.0
    average_reaction_time_ms: Mapped[int | None] = mapped_column(Integer, nullable=True)

    # ── Medication ────────────────────────────────────────────────────────────
    medications_scheduled: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    medications_taken: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    medication_adherence: Mapped[float | None] = mapped_column(Float, nullable=True)  # 0.0–1.0

    # ── Routines ──────────────────────────────────────────────────────────────
    routines_scheduled: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    routines_completed: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    routine_adherence: Mapped[float | None] = mapped_column(Float, nullable=True)  # 0.0–1.0

    # ── Assistant Engagement ──────────────────────────────────────────────────
    assistant_interactions_count: Mapped[int] = mapped_column(Integer, default=0, nullable=False)

    # ── CPI ───────────────────────────────────────────────────────────────────
    cpi_score: Mapped[float | None] = mapped_column(Float, nullable=True)  # 0–100

    computed_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=lambda: datetime.now(timezone.utc), nullable=False
    )

    def __repr__(self) -> str:
        return f"<DailyStatistic patient={self.patient_id} date={self.stat_date} cpi={self.cpi_score}>"


# ── cognitive_metrics ─────────────────────────────────────────────────────────

class CognitiveMetric(Base):
    """
    The four components of the Cognitive Performance Index (CPI).

    CPI formula (blueprint Section 9):
      CPI = 40% memory_accuracy
          + 25% reaction_performance
          + 20% completion_rate
          + 15% engagement_score

    All components are normalised to 0.0–1.0 before weighting.
    Final CPI is multiplied by 100 for display (e.g. 82).

    IMPORTANT: CPI is an assistive performance indicator,
               NOT a medical diagnosis or dementia severity score.
    """
    __tablename__ = "cognitive_metrics"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4
    )
    patient_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("patients.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    metric_date: Mapped[date] = mapped_column(Date, nullable=False, index=True)

    # CPI Component Scores (0.0–1.0)
    memory_accuracy: Mapped[float | None] = mapped_column(
        Float, nullable=True
    )  # From game session accuracy
    reaction_performance: Mapped[float | None] = mapped_column(
        Float, nullable=True
    )  # Normalised inverse of reaction_time_ms
    completion_rate: Mapped[float | None] = mapped_column(
        Float, nullable=True
    )  # (games_completed + medications_taken + routines_completed) / total
    engagement_score: Mapped[float | None] = mapped_column(
        Float, nullable=True
    )  # Based on assistant_interactions + games played

    # Final CPI (0–100)
    cpi_score: Mapped[float | None] = mapped_column(Float, nullable=True)

    # Trend vs previous day (positive = improvement)
    cpi_delta: Mapped[float | None] = mapped_column(Float, nullable=True)

    notes: Mapped[str | None] = mapped_column(String(500), nullable=True)
    computed_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=lambda: datetime.now(timezone.utc), nullable=False
    )

    def __repr__(self) -> str:
        return f"<CognitiveMetric patient={self.patient_id} date={self.metric_date} cpi={self.cpi_score}>"
